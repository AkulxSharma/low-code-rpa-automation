"""Regenerate docs/measured.md from the sweep's statistics file (read only).

usage: python3 scripts/refresh_measured.py <path to sweep-stats.csv>
Counts and timings only. n and the date range are on the first lines of the report.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from reader import report  # noqa: E402

HEADER = """# Measured from the live sweep

Generated by `python3 scripts/refresh_measured.py` from the sweep's per-cycle statistics file (counts and timings only). Regenerate to update; n is stated on every line.

"""
FOOTER = """
## What this does not show

- Blind-cycle durations are the time to reach the login page, not the time of a real pass. Pass durations come only from runs that got past login.
- Rows with approximate times (the backfilled rows) are left out of the replay.
- Dates are shown by month only, on purpose.
- No hours-saved figure: the manual check was never timed (see `comparison.md`).
"""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    body = report.build(sys.argv[1]).split("\n", 2)[2]  # drop the report's own title line
    from reader import stats
    own = stats.cycle_section(os.path.join(ROOT, "data", "rpa-cycles.csv"))
    with open(os.path.join(ROOT, "docs", "measured.md"), "w") as handle:
        handle.write(HEADER + body + ("\n" + own if own else "") + FOOTER)


if __name__ == "__main__":
    main()
